import test from 'node:test';
import assert from 'node:assert/strict';
import { sanitizeRichHtml, stripHtmlToText } from './sanitizer';
import { applyThemePreset, DEFAULT_DESIGN_SETTINGS, buildGoogleFontsUrl } from './themes';
import { generateWebsiteCode, generateWebsiteCss, prepareExportBodyHtml } from './codeGenerator';
import {
  createBlankDocument,
  parseDocumentFromHtmlFile,
  parseDocumentFromJson,
  serializeDocumentToJson,
} from './storage';

test('sanitizer strips scripts, event handlers, and javascript URLs while keeping safe formatting', () => {
  const dirty =
    '<h1 onclick="alert(1)">Hello</h1><script>evil()</script><p><a href="javascript:alert(2)">Bad</a> <a href="https://example.com" target="_blank" data-cta-button="true">Good CTA</a></p><img src="https://example.com/a.jpg" onerror="x()" alt="Photo">';
  const clean = sanitizeRichHtml(dirty);

  assert.equal(clean.includes('<script'), false);
  assert.equal(clean.includes('onclick'), false);
  assert.equal(clean.includes('onerror'), false);
  assert.equal(clean.includes('javascript:'), false);
  assert.equal(clean.includes('<h1>Hello</h1>'), true);
  assert.equal(clean.includes('data-cta-button="true"'), true);
  assert.equal(clean.includes('rel="noopener noreferrer"'), true);
  assert.equal(clean.includes('alt="Photo"'), true);
});

test('applyThemePreset updates tokens for newspaper, dark, and educational presets', () => {
  const dark = applyThemePreset(DEFAULT_DESIGN_SETTINGS, 'dark');
  assert.equal(dark.themePreset, 'dark');
  assert.equal(dark.mainBgColor, '#090d16');
  assert.equal(dark.headingColor, '#f8fafc');

  const educational = applyThemePreset(DEFAULT_DESIGN_SETTINGS, 'educational');
  assert.equal(educational.numberedHeadings, true);

  const newspaper = applyThemePreset(DEFAULT_DESIGN_SETTINGS, 'newspaper');
  assert.equal(newspaper.headingFont, 'Playfair Display');
  assert.equal(newspaper.bodyFont, 'Source Serif 4');
});

test('buildGoogleFontsUrl includes heading, body, and monospace fonts', () => {
  const url = buildGoogleFontsUrl('Playfair Display', 'Lora');
  assert.equal(url.includes('Playfair+Display'), true);
  assert.equal(url.includes('Lora'), true);
  assert.equal(url.includes('JetBrains+Mono'), true);
});

test('prepareExportBodyHtml wraps tables in .table-scroll, converts editor attributes to blog classes, and adds fallback alt', () => {
  const html =
    '<table><tr><th>A</th></tr><tr><td>1</td></tr></table><figure data-align="center"><img src="/pic.jpg"></figure><p><a href="/read" data-cta-button="true" data-btn-variant="outline">Read</a></p>';
  const prepared = prepareExportBodyHtml(html);

  assert.equal(prepared.includes('<div class="table-scroll">'), true);
  assert.equal(prepared.includes('<figure class="align-center">'), true);
  assert.equal(prepared.includes('class="btn btn-outline"'), true);
  assert.equal(prepared.includes('data-cta-button'), false);
  assert.equal(prepared.includes('data-align'), false);
  assert.equal(prepared.includes('alt="Blog post illustration"'), true);
});

test('generateWebsiteCss emits responsive rules, layout tokens, numbered headings, and omits unused element CSS', () => {
  const design = applyThemePreset(DEFAULT_DESIGN_SETTINGS, 'educational');
  const css = generateWebsiteCss(design, '<h1>Post</h1><p>Just a paragraph.</p>');

  assert.equal(css.includes('@media (max-width: 640px)'), true);
  assert.equal(css.includes('counter-reset: section-h2'), true);
  assert.equal(css.includes('--bg-page: #f0f7ff'), true);
  // Unused table/blockquote/lightbox CSS should not bloat a prose-only blog post
  assert.equal(css.includes('.table-scroll'), false);
  assert.equal(css.includes('.image-lightbox'), false);
});

test('generateWebsiteCode contains zero generator credits and emits clean blog HTML, CSS, JS, and ZIP assets', () => {
  const doc = createBlankDocument('My Field Post');
  doc.seo.metaDescription = 'A human-written blog post summary';
  doc.seo.author = 'Alex Rivera';
  doc.contentHtml =
    '<h1>Launch Notes</h1><p>Read more below.</p><img src="data:image/png;base64,iVBORw0KGgo=" alt="Logo" />';

  const result = generateWebsiteCode(doc);

  // Zero credits or generator prefixes anywhere in generated output
  const combined = `${result.indexHtml}\n${result.css}\n${result.js}\n${result.readmeMd}`;
  assert.equal(/FolioDraft|Generated by|created with/i.test(combined), false);
  assert.equal(combined.includes('fd-'), false);

  assert.equal(result.indexHtml.includes('<!DOCTYPE html>'), true);
  assert.equal(result.indexHtml.includes('<main class="blog-layout">'), true);
  assert.equal(result.indexHtml.includes('<article class="blog-post">'), true);
  assert.equal(result.indexHtml.includes('<meta name="description" content="A human-written blog post summary" />'), true);
  assert.equal(result.indexHtml.includes('<meta name="author" content="Alex Rivera" />'), true);
  assert.equal(result.indexHtml.includes('<link rel="stylesheet" href="style.css" />'), true);
  assert.equal(result.indexHtml.includes('<script src="script.js" defer></script>'), true);

  assert.equal(result.standaloneHtml.includes('<style>'), true);
  assert.equal(result.standaloneHtml.includes('<script>'), true);

  assert.equal(result.assets.length, 1);
  assert.equal(result.assets[0].path, 'assets/image-1.png');
  assert.equal(result.zipIndexHtml.includes('src="assets/image-1.png"'), true);
  assert.equal(result.zipIndexHtml.includes('data:image/png'), false);
});

test('generateWebsiteCode omits script tag when no interactive JS features are enabled', () => {
  const doc = createBlankDocument('Static Only Post');
  doc.design = {
    ...DEFAULT_DESIGN_SETTINGS,
    enableCodeCopy: false,
    enableImageLightbox: false,
    enableBackToTop: false,
  };
  doc.contentHtml = '<h1>Quiet Essay</h1><p>Pure HTML and CSS.</p>';

  const result = generateWebsiteCode(doc);
  assert.equal(result.js, '');
  assert.equal(result.indexHtml.includes('script.js'), false);
  assert.equal(result.standaloneHtml.includes('<script>'), false);
});

test('JSON export/import and HTML import preserve document content and metadata', () => {
  const doc = createBlankDocument('Exported Note');
  doc.contentHtml = '<h2>Section</h2><p>Paragraph text</p>';
  doc.design = applyThemePreset(DEFAULT_DESIGN_SETTINGS, 'magazine');

  const json = serializeDocumentToJson(doc);
  const restored = parseDocumentFromJson(json);

  assert.equal(restored.title, 'Exported Note');
  assert.equal(restored.design.themePreset, 'magazine');
  assert.equal(stripHtmlToText(restored.contentHtml).includes('Paragraph text'), true);

  const importedHtml = parseDocumentFromHtmlFile(
    '<!DOCTYPE html><html><head><title>Imported Doc</title><meta name="description" content="Hello SEO"></head><body><article><h1>Hi</h1><p>Body</p></article></body></html>'
  );
  assert.equal(importedHtml.title, 'Imported Doc');
  assert.equal(importedHtml.seo.metaDescription, 'Hello SEO');
  assert.equal(importedHtml.contentHtml.includes('<h1>Hi</h1>'), true);
});

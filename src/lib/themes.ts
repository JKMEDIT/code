export function getFontFamilyCss(fontId: string): string {
  const found = GOOGLE_FONTS.find((f) => f.id === fontId);
  return found ? found.familyCss : `'${fontId}', system-ui, sans-serif`;
}

export function buildGoogleFontsUrl(headingFont: string, bodyFont: string): string {
  const uniqueIds = Array.from(new Set([headingFont, bodyFont, 'JetBrains Mono']));
  const specs = uniqueIds
    .map((id) => GOOGLE_FONTS.find((f) => f.id === id)?.googleSpec)
    .filter((s): s is string => Boolean(s));
  if (specs.length === 0) return '';
  return `https://fonts.googleapis.com/css2?${specs.map((s) => `family=${s}`).join('&')}&display=swap`;
}

export function applyThemePreset(
  current: DesignSettings,
  presetId: ThemePresetId
): DesignSettings {
  const preset = THEME_PRESETS.find((p) => p.id === presetId);
  if (!preset || presetId === 'custom') {
    return { ...current, themePreset: presetId };
  }
  return {
    ...current,
    ...preset.tokens,
    numberedHeadings: preset.tokens.numberedHeadings ?? false,
    themePreset: presetId,
  };
}
